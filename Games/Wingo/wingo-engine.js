    function winResultNow(t, issue) {
        var k = String(issue);
        /* settle FIRST: the app asks for this the instant the round ends,
           so the win/loss it shows must already be decided */
        settle(t);
        var r = resultFor(t, k);
        var bets = getBets(t), best = null, mine = 0, i;
        for (i = 0; i < bets.length; i++) {
            var b = bets[i];
            if (b.issuenumber !== k) continue;
            mine++;
            if (b.settled && b.state === 1 && (!best || b.profitAmount > best.profitAmount)) best = b;
        }
        /* no bet on this period -> nothing to pop up (matches the real API) */
        if (!mine) return ok([]);
        /* draw not ready yet -> don't answer (never a wrong LOSS) */
        if (!r) return ok([]);
        return ok([{
            issueNumber: k,
            number: r.number,
            colour: r.colour,
            winAmount: best ? best.profitAmount : 0,
            typeName: t,
            state: best ? 1 : 0
        }]);
    }

    function hWinResult(t, issue) {
        var k = String(issue), p = periodFromIssue(t, k);
        /* the app polls for the popup right around the draw moment; when it
           asks even a moment early, HOLD this response until the round ends
           so the win/loss pops up the instant the countdown hits 0 */
        if (p && Date.now() < p.end) {
            var ms = Math.min((p.end + 80) - Date.now(), 65000);
            if (ms > 0) return { __hold: ms, t: t, issue: k };
        }
        return winResultNow(t, k);
    }

    function hBetting(t, p) {
        if (!bettingOpen(t)) return fail(1, 'The current period is settled');

        var unit = parseFloat(p.amount) || 0;
        var cnt = parseInt(p.betCount, 10) || 1;
        if (unit < 1) return fail(7, "Invalid value for parameter 'Amount'");
        if (cnt < 1) return fail(7, "Invalid value for parameter 'BetCount'");

        var stake = r2(unit * cnt);
        var bal = getBalance();
        if (bal < stake) return fail(1, 'Balance is not enough');

        var issue = String(p.issuenumber || p.issueNumber || periodAt(t, Date.now()).issue);
        var bets = getBets(t);

        setBalance(bal - stake);
        bets.unshift({
            orderNumber: bets.length + 1,
            issuenumber: issue,
            selectType: p.selectType,
            gameType: p.gameType,
            amount: r2(unit),
            betCount: cnt,
            typeId: t,
            state: 2,
            settled: false,
            realAmount: r2(stake * 0.98),
            fee: r2(stake * 0.02),
            addTime: nowStr(),
            premium: String(rndInt(10000, 99999))
        });
        if (bets.length > MAX_BETS) bets.length = MAX_BETS;
        jset(betsKey(t), bets);

        return ok({ amount: stake, balance: getBalance() });
    }

