    function jget(k, d) {
        try { var v = LS.getItem(k); return (v === null || v === undefined) ? d : JSON.parse(v); }
        catch (e) { return d; }
    }
    function jset(k, v) { try { LS.setItem(k, JSON.stringify(v)); } catch (e) { } }
    function sget(k, d) { try { var v = LS.getItem(k); return (v === null || v === undefined) ? d : v; } catch (e) { return d; } }
    function sset(k, v) { try { LS.setItem(k, v); } catch (e) { } }

