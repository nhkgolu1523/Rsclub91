/* ============================================================
   WINGO INDEPENDENT ENGINE   (v2 - complete)
   ------------------------------------------------------------
   * 100% standalone. NO backend, NO api, NO login, NO network.
   * Every /api/webapi/* request made by the app is captured
     here and answered by this engine.
   * Results : REAL results only, read from Firebase
               (GAME-RESULTS/WINGO/<MODE>), generated by the
               Cloudflare Worker. The app NEVER invents a number.
   * History : latest 500 FINISHED periods per mode (50 pages x 10),
               straight from Firebase; refresh = instant real data.
   * Balance : own wallet, starts at 10000.
   * Bets    : own order book, settled by the real results.
   * Stats   : Frequency / Missing / Max Continued / Avg Missing
               / Interval Number computed from real history.
   * Response shapes replicate the original PHP API 1:1 so the
     website UI stays byte-for-byte the same (no UI changes).
   ============================================================ */
