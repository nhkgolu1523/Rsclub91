    /* ================= random ================= */
    function rnd10() {
        var c = W.crypto || W.msCrypto;
        if (!c || !c.getRandomValues) return Math.floor(Math.random() * 10);
        var a = new Uint32Array(1), max = Math.floor(4294967296 / 10) * 10;
        do { c.getRandomValues(a); } while (a[0] >= max);
        return a[0] % 10;
    }
    function rndInt(min, max) { return min + Math.floor(Math.random() * (max - min + 1)); }

    /* ================= time / period / issue ================= */
    function pad(n, l) { n = String(n); while (n.length < l) n = '0' + n; return n; }
    function fmtTime(ms) {
        var d = new Date(ms);
        return d.getFullYear() + '-' + pad(d.getMonth() + 1, 2) + '-' + pad(d.getDate(), 2) +
            ' ' + pad(d.getHours(), 2) + ':' + pad(d.getMinutes(), 2) + ':' + pad(d.getSeconds(), 2);
    }
    function nowStr() { return fmtTime(Date.now()); }

    function issueFor(t, startMs) {
        var c = cfg(t), d = new Date(startMs);
        var dayStart = new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime();
        var idx = Math.floor((startMs - dayStart) / (c.iv * 1000)) + 1;
        return '' + d.getFullYear() + pad(d.getMonth() + 1, 2) + pad(d.getDate(), 2) + c.seq + pad(idx, c.len);
    }
    function periodAt(t, ms) {
        var iv = cfg(t).iv * 1000, start = Math.floor(ms / iv) * iv;
        return { start: start, end: start + iv, issue: issueFor(t, start) };
    }
    function periodFromIssue(t, issue) {
        var c = cfg(t), s = String(issue), need = 8 + c.seq.length + c.len;
        if (s.length < need) return null;
        var y = +s.substr(0, 4), mo = +s.substr(4, 2) - 1, da = +s.substr(6, 2);
        var idx = parseInt(s.substr(8 + c.seq.length), 10);
        if (!y || isNaN(idx) || idx < 1) return null;
        var start = new Date(y, mo, da).getTime() + (idx - 1) * c.iv * 1000;
        return { start: start, end: start + c.iv * 1000, issue: s };
    }
    function typeOfIssue(issue) {
        var s = String(issue), p5 = s.substr(8, 5), p6 = s.substr(8, 6);
        if (p6 === '100020') return 2;
        if (p5 === '10101') return 3;
        if (p5 === '10030') return 30;
        if (p5 === '10004') return 4;
        if (p5 === '10001') return 1;
        return 1;
    }
    function bettingOpen(t) {
        var p = periodAt(t, Date.now());
        return Date.now() < (p.end - cfg(t).draw * 1000);
    }

    /* ================= colour / size ================= */
    function colourOf(n) {
        if (n === 0) return 'red,violet';
        if (n === 5) return 'green,violet';
        return (n % 2 === 1) ? 'green' : 'red';
    }
    function sizeOf(n) { return n >= 5 ? 'Big' : 'Small'; }

    /* ================= result generation ================= */
    /* Results are produced ONLY by the Cloudflare Worker and read from
       Firebase. The app never generates, invents or mutates a result. */

    /* deterministic 5-digit "premium" so one period always shows the same value */
    function premiumOf(issue, n) {
        var s = String(issue), hsh = 7;
        for (var i = 0; i < s.length; i++) hsh = ((hsh * 31) + s.charCodeAt(i)) % 100000;
        return String(10000 + ((hsh * 7 + n * 997) % 90000));
    }

    /* full history row built from an issue id + its number */
    function rowOf(t, issue, n) {
        var p = periodFromIssue(t, issue);
        return {
            issueNumber: String(issue),
            number: n,
            colour: colourOf(n),
            premium: premiumOf(issue, n),
            _p: p ? p.start : 0
        };
    }

    /* ================= history (Firebase-backed) ================= */
    /* cache key version bumped: drops any previously stored FAKE history */
    function histKey(t) { return 'we_hist2_' + t; }

    /* in-memory history cache (avoids parse/stringify on every poll) */
    var _cache = {};

    /* per-mode Firebase state:
       _fb[t] = { map:{issue:number}, loaded, at, filled, at2, builtFor } */
    var _fb = {};
    function fbState(t) {
        if (!_fb[t]) _fb[t] = { map: {}, loaded: false, at: 0, filled: false, at2: 0, builtFor: '' };
        return _fb[t];
    }

    function fbModeUrl(t) { return FB_BASE + '/' + FB_BRANCH + '/' + FB_MODE[t]; }
    function fbModeJson(t) { return fbModeUrl(t) + '.json'; }
    function fbOneUrl(t, issue) { return fbModeUrl(t) + '/' + issue + '.json'; }

    /* plain XHR (the engine's own interceptor lets non-API urls through) */
    function ajax(method, url, body, cb) {
        var x;
        try {
            x = new XMLHttpRequest();
            x.open(method, url, true);
            x.setRequestHeader('Content-Type', 'application/json');
            x.timeout = FB_TIMEOUT;
            x.onreadystatechange = function () {
                if (x.readyState !== 4) return;
                if (!cb) return;                       /* fire-and-forget writes */
                if (x.status >= 200 && x.status < 300) cb(null, x.responseText);
                else cb(new Error('HTTP ' + x.status));
            };
            x.onerror = function () { if (cb) cb(new Error('network')); };
            x.ontimeout = function () { if (cb) cb(new Error('timeout')); };
            x.send(body === undefined ? null : body);
        } catch (e) { if (cb) cb(e); }
        return x;
    }

    /* rebuild the visible history from the Firebase map,
       hiding periods that have not finished yet */
    function rebuild(t) {
        var st = fbState(t), keys = Object.keys(st.map), h = [], i, p, n;
        for (i = 0; i < keys.length; i++) {
            n = parseInt(st.map[keys[i]], 10);
            if (isNaN(n) || n < 0 || n > 9) continue;
            p = periodFromIssue(t, keys[i]);
            if (!p || p.end > Date.now()) continue;      /* running -> hidden */
            h.push(rowOf(t, keys[i], n));
        }
        h.sort(function (a, b) { return b._p - a._p; });
        if (h.length > FB_HIST) h.length = FB_HIST;   /* exactly 50 rows */
        _cache[t] = h;
        jset(histKey(t), h);
        return h;
    }

    /* No local/fake generation. Before Firebase answers, only previously
       cached REAL data (localStorage) is shown - never invented numbers. */
    function seedLocal(t) {
        _cache[t] = [];
        return _cache[t];
    }

    function loadLocal(t) {
        if (_cache[t]) return _cache[t];
        var h = jget(histKey(t), null);
        if (h && h.length) { _cache[t] = h; return h; }
        return null;
    }

    function histList(t) {
        var h = loadLocal(t);
        return h || seedLocal(t);
    }

    /* ---- prune the in-memory map to the newest FB_HIST FINISHED periods.
            READ-ONLY: never invents a value. Missing periods are left
            missing (Firebase/Worker is the only source of results). */
    function ensureFilled(t) {
        var st = fbState(t), now = Date.now();

        if (!st.loaded) return;

        var keys = Object.keys(st.map), i, p;
        var finished = [];
        for (i = 0; i < keys.length; i++) {
            p = periodFromIssue(t, keys[i]);
            if (!p) continue;
            /* keep the running period + all future (upcoming) ones out of
               the "finished" window; they are never rendered anyway */
            if (p.end <= now) finished.push({ key: keys[i], start: p.start });
        }

        /* only prune when we have more finished rows than we display */
        if (finished.length <= FB_HIST) { st.filled = true; return; }

        finished.sort(function (a, b) { return b.start - a.start; });
        var keep = {};
        /* keep newest FB_HIST finished + every not-yet-finished (running/future) */
        for (i = 0; i < FB_HIST && i < finished.length; i++) keep[finished[i].key] = true;
        for (i = 0; i < keys.length; i++) {
            p = periodFromIssue(t, keys[i]);
            if (p && p.end > now) keep[keys[i]] = true;
        }
        var pruned = {};
        for (i = 0; i < keys.length; i++) if (keep[keys[i]]) pruned[keys[i]] = st.map[keys[i]];
        st.map = pruned;
        st.filled = true;
        rebuild(t);
    }

    /* result of the running period - READ-ONLY, Firebase only.
       If the Worker has not written it yet we return nothing (the UI
       simply keeps waiting) - we never invent a value. */
    function ensureCurrent(t) {
        var st = fbState(t), issue = periodAt(t, Date.now()).issue;
        if (st.map[issue] !== undefined) return st.map[issue];
        return undefined;
    }

    /* pull every mode from Firebase in ONE request, then top up */
    function fbRefresh(cb) {
        ajax('GET', FB_BASE + '/' + FB_BRANCH + '.json', undefined, function (err, txt) {
            if (err) { if (cb) cb(err); return; }
            var all = {};
            try { all = JSON.parse(txt) || {}; } catch (e) { all = {}; }
            TYPE_ORDER.forEach(function (t) {
                var m = all[FB_MODE[t]];
                var st = fbState(t);
                var server = (m && typeof m === 'object' && !Array.isArray(m)) ? m : {};
                /* MERGE instead of replace: values we just wrote may not be
                   in the returned snapshot yet, and a period's value must
                   never be lost or re-generated after the round started. */
                var merged = {}, k;
                for (k in server) merged[k] = server[k];
                for (k in st.map) if (merged[k] === undefined) merged[k] = st.map[k];
                st.map = merged;
                st.loaded = true;
                st.at = Date.now();
            });
            TYPE_ORDER.forEach(function (t) { ensureFilled(t); rebuild(t); settle(t); });
            if (cb) cb(null);
        });
    }

    var _fbTimer = null, _fbTick = null;
    function fbStart() {
        fbRefresh(function () { });
        if (_fbTimer) clearInterval(_fbTimer);
        _fbTimer = setInterval(function () { fbRefresh(function () { }); }, FB_POLL);
        /* keep the running period's value written even when the UI is idle.
           500ms: draw hone ke baad settle + popup turant (1s me delay mehsoos hota tha) */
        if (_fbTick) clearInterval(_fbTick);
        _fbTick = setInterval(function () {
            TYPE_ORDER.forEach(function (t) {
                if (fbState(t).loaded) { ensureCurrent(t); settle(t); }
            });
        }, 500);
    }

    /* while Firebase has not answered yet, show only previously cached REAL
       history (localStorage). Never generate/invent numbers. */
    function localSync(t) {
        var h = loadLocal(t);
        return h || seedLocal(t);
    }

    /* single entry point used by every handler */
    function sync(t) {
        var st = fbState(t);
        if (!st.loaded) return localSync(t);
        var newest = periodAt(t, Date.now() - cfg(t).iv * 1000).issue;
        if (st.builtFor !== newest) { st.builtFor = newest; return rebuild(t); }
        return _cache[t] || rebuild(t);
    }

    function resultFor(t, issue) {
        var k = String(issue), st = fbState(t);

        /* Firebase is the source of truth: the value written by the Worker */
        if (st.map[k] !== undefined) {
            var pe = periodFromIssue(t, k);
            if (pe && pe.end > Date.now()) return null;    /* not revealed yet */
            var rn = parseInt(st.map[k], 10);
            if (!isNaN(rn) && rn >= 0 && rn <= 9) return rowOf(t, k, rn);
        }

        var h = sync(t), i;
        for (i = 0; i < h.length; i++) if (h[i].issueNumber === k) return h[i];

        /* not in Firebase (yet) -> no result. Never invent a number. */
        return null;
    }

